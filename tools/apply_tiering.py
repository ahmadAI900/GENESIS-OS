"""Apply the rules in tiering_rules.py to the evidence, and print a review.

Reads:
    docs/fast_gate_evidence.json    dynamic (what ran)
    docs/fast_gate_static_scan.json static  (what the source contains)

Writes:
    docs/tests_tiering.json         node id -> tier + reasons

A test is `runtime` only when BOTH signals agree it is harmless:

  - no forbidden dynamic event (GUI, browser, OS launch, non-loopback
    network, non-allowlisted executable, GUI window-station ctypes call)
  - under the duration limit
  - no unexplained static signal

Anything else stays `live`. `live` is the safe direction: it costs gate
time, it never hides a real GUI dependency. Marking a test `runtime` on
weak evidence is the failure mode this whole exercise exists to prevent,
so every move is justified by a named rule and printed for review.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

import tiering_rules as rules  # noqa: E402


def static_by_test(scan: dict) -> dict:
    """nodeid-ish -> signal set, mirroring cross_check's scoping."""
    out = {}
    for filename, entry in scan.get("files", {}).items():
        per_test = {}
        for block in entry.get("tests", []):
            per_test[block["test"]] = {s["signal"] for s in block["signals"]}
        file_signals = set(entry.get("signals", []))
        for label, signals in per_test.items():
            key = f"{filename}::{label}"
            out[key] = signals
        out[filename] = file_signals
        out[f"{filename}::__file__"] = file_signals
    return out


def signals_for(index: dict, nodeid: str) -> set:
    out = set()
    for candidate in rules.static_keys_for(nodeid):
        out |= index.get(candidate, set())
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", default=str(BACKEND / "docs" /
                                                 "fast_gate_evidence.json"))
    parser.add_argument("--scan", default=str(BACKEND / "docs" /
                                              "fast_gate_static_scan.json"))
    parser.add_argument("--out", default=str(BACKEND / "docs" /
                                             "tests_tiering.json"))
    parser.add_argument("--summary", default=str(BACKEND / "docs" /
                                                "tests_tiering_summary.md"))
    args = parser.parse_args(argv)

    evidence = json.loads(Path(args.evidence).read_text(encoding="utf-8"))
    scan = json.loads(Path(args.scan).read_text(encoding="utf-8"))
    index = static_by_test(scan)

    tiers = {}
    for nodeid, record in sorted(evidence.items()):
        if nodeid.startswith("__"):
            continue
        signals = signals_for(index, nodeid)
        # The recorder's own tests assert on the recorder: they use
        # subprocess and the GUI libraries on purpose. They are exempt by
        # filename, narrowly -- see RECORDER_SELF_TESTS in tiering_rules.
        exempt = ()
        explained = ()
        if rules.is_recorder_self_test(nodeid):
            exempt = rules.RECORDER_SELF_TEST_EXEMPT_KINDS
            explained = signals
        tier, reasons = rules.classify(
            record.get("events", []), record.get("seconds"), signals,
            explained, exempt_kinds=exempt)
        tiers[nodeid] = {"tier": tier, "reasons": reasons}

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(
        {"__meta__": {
            "tests": len(tiers),
            "live": sum(1 for t in tiers.values() if t["tier"] == "live"),
            "runtime": sum(1 for t in tiers.values() if t["tier"] == "runtime"),
            "duration_limit_seconds": rules.DURATION_LIMIT_SECONDS,
        }, **{k: v for k, v in tiers.items()}},
        indent=1, sort_keys=True), encoding="utf-8")

    # ---- review summary -------------------------------------------------
    per_file = defaultdict(lambda: {"live": 0, "runtime": 0})
    live_tests, runtime_tests = [], []
    for nodeid, data in tiers.items():
        bucket = per_file[nodeid.split("::")[0]]
        bucket[data["tier"]] += 1
        (live_tests if data["tier"] == "live" else runtime_tests).append(nodeid)

    lines = []
    add = lines.append
    add("# Tiering review summary")
    add("")
    add(f"Generated by `tools/apply_tiering.py` from "
        f"`{Path(args.evidence).name}` and `{Path(args.scan).name}`.")
    add("")
    add(f"- tests classified: **{len(tiers)}**")
    add(f"- `live`: **{len(live_tests)}**")
    add(f"- `runtime`: **{len(runtime_tests)}**")
    add(f"- duration limit: {rules.DURATION_LIMIT_SECONDS}s")
    add("")
    add("## Counts per file")
    add("")
    add("| file | live | runtime |")
    add("|---|---:|---:|")
    for filename in sorted(per_file):
        row = per_file[filename]
        add(f"| {filename} | {row['live']} | {row['runtime']} |")
    add("")
    add("## Every live test, with the rule that kept it live")
    add("")
    add("| node id | reasons |")
    add("|---|---|")
    for nodeid in sorted(live_tests):
        reasons = "; ".join(tiers[nodeid]["reasons"])
        add(f"| `{nodeid}` | {reasons} |")
    add("")

    # ---- what moved, in both directions -------------------------------
    previous_live = _previous_live(args.evidence, tiers)
    demoted = sorted(set(previous_live) - set(live_tests) & set(tiers))
    promoted = sorted(set(live_tests) & set(tiers) - set(previous_live))

    add("## Moves out of `live` into the fast gate")
    add("")
    add(f"{len(demoted)} test(s) moved `live` -> `runtime`. Each one "
        "recorded no forbidden event, ran under the duration limit, and "
        "had no unexplained static signal. No test body was edited; the "
        "move is applied by `conftest.py` reading "
        "`docs/tests_tiering.json`.")
    add("")
    add("| node id | tier |")
    add("|---|---|")
    for nodeid in demoted:
        add(f"| `{nodeid}` | runtime |")
    add("")

    add("## Moves into `live` (were previously in the fast gate)")
    add("")
    add(f"{len(promoted)} test(s) moved `runtime` -> `live`. Every one "
        "recorded a forbidden event. These were running in the fast gate "
        "while touching a real window station, a real browser, or the "
        "real network.")
    add("")
    add("| node id | reason |")
    add("|---|---|")
    for nodeid in promoted:
        reasons = "; ".join(tiers[nodeid]["reasons"])
        add(f"| `{nodeid}` | {reasons} |")
    add("")

    Path(args.summary).write_text("\n".join(lines), encoding="utf-8")

    print(f"classified {len(tiers)} tests")
    print(f"  live    : {len(live_tests)}")
    print(f"  runtime : {len(runtime_tests)}")
    print(f"  moved live -> runtime : {len(demoted)}")
    print(f"  moved runtime -> live : {len(promoted)}")
    print(f"-> {out}")
    print(f"-> {args.summary}")
    return 0


def _previous_live(evidence_path, tiers):
    """Node ids that were NOT in the fast-tier run file, i.e. were live.

    Derived from the recorded fast-tier run rather than from a stored
    list, so the summary cannot drift from the evidence it describes.
    """
    fast_run = Path(args_fast_run())
    if not fast_run.is_file():
        return set(tiers)
    data = json.loads(fast_run.read_text(encoding="utf-8"))
    observed_fast = {k for k in data if not k.startswith("__")}
    return {n for n in tiers if n not in observed_fast}


def args_fast_run():
    return BACKEND / "docs" / "fast_gate_runs" / "fast.json"


if __name__ == "__main__":
    raise SystemExit(main())