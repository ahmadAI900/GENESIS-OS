#!/usr/bin/env python
"""Browser truthfulness under load, with REAL probes and NO fixture.

    python tools/verify/verify_browser_truthfulness.py
    python tools/verify/verify_browser_truthfulness.py --runs 20 --load 3

Why this exists
---------------
Continuation C1 made the deterministic-probe fixture pin the provider
probe caches, and the flaky test then passed. That proves the FIXTURE
works. It proves nothing about the product, because the fixture's whole
job is to bypass the probe. So this script removes the fixture and
measures what `GenesisOS` actually reports while the machine is busy.

The claim under test is a truthfulness claim, not an availability claim:

    either the provider list is the FULL healthy list,
    or browser_degraded is true and says why.

A run that is missing a provider AND reports `degraded = False` is a
failure, because the runtime is telling the operator it is fully
functional while a capability is missing for a reason it has not
disclosed. That is the exact defect class the degraded flag was added to
surface, so an unverified degraded flag would make the flag decorative.

Method
------
Each run is a FRESH PROCESS. That is not a detail: `_probe_cache` is a
module-level global, so a second `GenesisOS()` in the same process reads
a cached answer and can never observe a fresh probe. A same-process loop
would report the first run twenty times.

Load is generated by real CPU-burning sibling processes, so the probe's
5-second join bound is contended the way it is during a full suite run.

Exit code is non-zero if ANY run is untruthful, or if the recovery check
does not recover.
"""

from __future__ import annotations

import argparse
import json
import multiprocessing
import os
import subprocess
import sys
import time
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent.parent
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

RESULT_SENTINEL = "@@C2-BROWSER-RESULT@@"

# The provider list the product claims to support when nothing is wrong.
# `test_phase5_provider_registry.py::test_browser_manager_has_three_
# concrete_providers` asserts exactly these three, so "the full healthy
# list" is the product's own contract, not this script's invention.
HEALTHY_LIST = ["playwright", "selenium", "webbrowser"]

# Modes
MODE_PROBE = "probe"
MODE_RECOVERY = "recovery"


def _burn(seconds: float):
    """A CPU burner. No sleep: it must occupy a core, not poll."""
    end = time.time() + seconds
    x = 0
    while time.time() < end:
        for _ in range(20000):
            x += 1
    return x


def _child_env():
    env = dict(os.environ)
    # Real probes: no fixture, no pinning, no stub. This script is
    # deliberately outside the fast gate for the same reason.
    env.pop("GENESIS_MUTATION", None)
    env["PYTHONIOENCODING"] = "utf-8"
    return env


# ----------------------------------------------------------------------
# Child: one construction, one JSON verdict
# ----------------------------------------------------------------------

def child_probe() -> int:
    import genesis_os.browser_playwright as pw
    import genesis_os.browser_selenium as se

    started = time.time()
    from genesis import GenesisOS

    runtime = GenesisOS()
    elapsed = time.time() - started

    names = runtime.browser_provider_names
    degraded = bool(runtime.browser_degraded)
    reason = runtime.browser_degraded_reason

    caches = {
        "playwright": {"value": pw._probe_cache, "kind": pw._probe_cache_kind},
        "selenium": {"value": se._probe_cache, "kind": se._probe_cache_kind},
    }

    missing = sorted(set(HEALTHY_LIST) - set(names))
    if sorted(names) == sorted(HEALTHY_LIST) and not degraded:
        verdict = "HEALTHY"
    elif degraded:
        verdict = "DEGRADED"
    else:
        verdict = "UNTRUTHFUL"

    print(RESULT_SENTINEL + json.dumps({
        "mode": MODE_PROBE,
        "verdict": verdict,
        "providers": names,
        "degraded": degraded,
        "reason": reason,
        "missing": missing,
        "probe_caches": caches,
        "construct_seconds": round(elapsed, 2),
    }))
    return 0


def child_recovery(wait_seconds: float) -> int:
    """Construct, observe, wait past the probe TTL, construct again.

    The TTL is what C1 added so a timed-out probe is retried. This is
    the only measurement that shows the retry actually happens.
    """
    import genesis_os.browser_playwright as pw
    import genesis_os.browser_selenium as se
    from genesis import GenesisOS

    before_runtime = GenesisOS()
    before = {
        "providers": before_runtime.browser_provider_names,
        "degraded": bool(before_runtime.browser_degraded),
        "pw": (pw._probe_cache, pw._probe_cache_kind),
        "se": (se._probe_cache, se._probe_cache_kind),
    }

    ttl = getattr(se, "_PROBE_CACHE_TTL_SECONDS", 60.0)
    waited = max(wait_seconds, ttl + 5.0)
    time.sleep(waited)

    after_runtime = GenesisOS()
    after = {
        "providers": after_runtime.browser_provider_names,
        "degraded": bool(after_runtime.browser_degraded),
        "pw": (pw._probe_cache, pw._probe_cache_kind),
        "se": (se._probe_cache, se._probe_cache_kind),
    }

    recovered = sorted(after["providers"]) == sorted(HEALTHY_LIST)
    print(RESULT_SENTINEL + json.dumps({
        "mode": MODE_RECOVERY,
        "verdict": "RECOVERED" if recovered else "NOT_RECOVERED",
        "ttl_seconds": ttl,
        "waited_seconds": round(waited, 1),
        "before": before,
        "after": after,
        "recovered": recovered,
    }))
    return 0


def run_child(mode: str, args, timeout=300):
    """Launch one FRESH child process in `mode` and return its verdict."""
    proc = subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), "--child", mode,
         "--wait", str(args.wait)],
        cwd=BACKEND, env=_child_env(), capture_output=True, text=True,
        timeout=timeout)
    for line in proc.stdout.splitlines():
        if line.startswith(RESULT_SENTINEL):
            return json.loads(line[len(RESULT_SENTINEL):])
    raise RuntimeError(
        f"child produced no verdict (exit {proc.returncode}).\n"
        f"--- stdout tail ---\n{proc.stdout[-2000:]}\n"
        f"--- stderr tail ---\n{proc.stderr[-2000:]}")


# ----------------------------------------------------------------------
# Parent
# ----------------------------------------------------------------------

def start_load(n_burners: int, seconds: float):
    procs = [multiprocessing.Process(target=_burn, args=(seconds,),
                                     daemon=True)
             for _ in range(n_burners)]
    for p in procs:
        p.start()
    return procs


def stop_load(procs):
    for p in procs:
        p.join(timeout=5)
        if p.is_alive():
            p.terminate()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=int, default=20)
    parser.add_argument("--load", type=int, default=3,
                        help="number of CPU-burning sibling processes")
    parser.add_argument("--wait", type=float, default=0.0,
                        help="recovery check: seconds to wait (min TTL+5)")
    parser.add_argument("--child", choices=(MODE_PROBE, MODE_RECOVERY),
                        help=argparse.SUPPRESS)
    parser.add_argument("--json-out", help="write the raw run records here")
    args = parser.parse_args(argv)

    if args.child:
        if args.child == MODE_RECOVERY:
            return child_recovery(args.wait)
        return child_probe()

    print("browser truthfulness under load -- REAL probes, NO fixture")
    print(f"  logical CPUs        : {os.cpu_count()}")
    print(f"  runs                : {args.runs}, fresh process each")
    print(f"  CPU load            : {args.load} burner process(es) "
          f"(target ~{args.load}x)")
    print(f"  full healthy list   : {sorted(HEALTHY_LIST)}")
    print()

    burn_seconds = args.runs * 60 + 600
    load = start_load(args.load, burn_seconds)
    time.sleep(1.0)
    records = []
    try:
        for index in range(1, args.runs + 1):
            try:
                record = run_child(MODE_PROBE, args)
            except (RuntimeError, subprocess.TimeoutExpired) as error:
                print(f"  run {index:2d}/{args.runs}: CHILD FAILED: "
                      f"{str(error)[:300]}")
                records.append({"mode": MODE_PROBE,
                                "verdict": "CHILD_FAILED",
                                "error": str(error)[:800]})
                continue
            records.append(record)
            caches = record["probe_caches"]
            print(f"  run {index:2d}/{args.runs}: {record['verdict']:<11} "
                  f"providers={record['providers']} "
                  f"degraded={record['degraded']} "
                  f"pw={caches['playwright']['value']}/"
                  f"{caches['playwright']['kind']} "
                  f"se={caches['selenium']['value']}/"
                  f"{caches['selenium']['kind']} "
                  f"({record['construct_seconds']}s)")
            sys.stdout.flush()
    finally:
        stop_load(load)

    print()
    print("recovery check (wait past the probe TTL, then reconstruct)")
    print("-" * 70)
    recovery = None
    try:
        recovery = run_child(MODE_RECOVERY, args, timeout=600)
        print(f"  TTL {recovery['ttl_seconds']}s, waited "
              f"{recovery['waited_seconds']}s")
        print(f"  before: providers={recovery['before']['providers']} "
              f"degraded={recovery['before']['degraded']} "
              f"se_cache={recovery['before']['se']}")
        print(f"  after : providers={recovery['after']['providers']} "
              f"degraded={recovery['after']['degraded']} "
              f"se_cache={recovery['after']['se']}")
        print(f"  verdict: {recovery['verdict']}")
    except (RuntimeError, subprocess.TimeoutExpired) as error:
        print(f"  RECOVERY CHECK FAILED: {str(error)[:400]}")
    print()

    # ---------------- distribution ----------------
    probes = [r for r in records if r.get("mode") == MODE_PROBE]
    counts = {}
    for r in probes:
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    print("DISTRIBUTION")
    print("-" * 70)
    for verdict in sorted(counts):
        print(f"  {verdict:<12} {counts[verdict]}")
    print()

    untruthful = [r for r in probes if r["verdict"] == "UNTRUTHFUL"]
    degraded = [r for r in probes if r["verdict"] == "DEGRADED"]
    healthy = [r for r in probes if r["verdict"] == "HEALTHY"]

    if degraded:
        reasons = {}
        for r in degraded:
            reasons[r["reason"]] = reasons.get(r["reason"], 0) + 1
        print("degraded reasons:")
        for reason, n in reasons.items():
            names = sorted({p for r in degraded if r["reason"] == reason
                            for p in r["missing"]})
            print(f"  {n}x  {reason!r}  missing providers named: {names}")
        print()

    if untruthful:
        print("UNTRUTHFUL RUNS (providers missing, degraded=False)")
        print("-" * 70)
        reasons_seen = set()
        for r in untruthful:
            key = (tuple(r["missing"]), r["probe_caches"]["selenium"]["kind"],
                   r["probe_caches"]["playwright"]["kind"])
            if key in reasons_seen:
                continue
            reasons_seen.add(key)
            print(f"  missing={r['missing']}  "
                  f"selenium_cache={r['probe_caches']['selenium']['value']}"
                  f"/{r['probe_caches']['selenium']['kind']}  "
                  f"playwright_cache={r['probe_caches']['playwright']['value']}"
                  f"/{r['probe_caches']['playwright']['kind']}")
        print()

    if args.json_out:
        Path(args.json_out).write_text(json.dumps(
            {"runs": records, "recovery": recovery}, indent=2),
            encoding="utf-8")
        print(f"raw records: {args.json_out}")

    print()
    ok = True
    if not probes:
        print("RESULT: FAIL -- no runs completed")
        return 1
    if len(probes) != args.runs:
        print(f"RESULT: FAIL -- only {len(probes)}/{args.runs} runs "
              f"completed")
        ok = False
    if untruthful:
        print(f"RESULT: FAIL -- {len(untruthful)}/{len(probes)} runs were "
              f"UNTRUTHFUL: providers missing while degraded=False")
        ok = False
    if recovery is None or not recovery.get("recovered"):
        print("RESULT: FAIL -- recovery check did not return to the full "
              "healthy list after the TTL")
        ok = False
    if ok:
        print(f"RESULT: PASS -- {len(healthy)} healthy, {len(degraded)} "
              f"degraded, 0 untruthful; recovery confirmed")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())